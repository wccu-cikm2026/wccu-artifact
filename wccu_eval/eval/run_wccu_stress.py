from __future__ import annotations

import argparse
import json
import os
import random
from pathlib import Path
from typing import Any

from wccu_eval.eval.run_experiment import REPO_ROOT, aggregate
from wccu_eval.scheduler.context_concurrency_policy import PolicyMode
from wccu_eval.scheduler.team_dag_executor import execute_context_policy_parallel
from wccu_eval.substrate.context_substrate_store import seed_context
from wccu_eval.utils import ensure_dir, now_iso, remove_dir, stable_hash, write_json, append_jsonl

DEFAULT_CONDITIONS = [
    'adaptive_wccu_execution_trace',
    'adaptive_wccu_projection_trace',
    'adaptive_policy',
    'adaptive_readset_occ',
    'uniform_snapshot_occ',
    'uniform_review_gated',
    'uniform_append_only',
]

CONDITION_TO_POLICY = {
    'adaptive_wccu_execution_trace': PolicyMode.ADAPTIVE_WCCU_EXECUTION_TRACE,
    'adaptive_wccu_projection_trace': PolicyMode.ADAPTIVE_WCCU_PROJECTION_TRACE,
    'adaptive_wccu_model_certificate': PolicyMode.ADAPTIVE_WCCU_MODEL_CERTIFICATE,
    'adaptive_wccu_no_read_validation': PolicyMode.ADAPTIVE_WCCU_NO_READ_VALIDATION,
    'adaptive_wccu_oracle_dependency': PolicyMode.ADAPTIVE_WCCU_ORACLE_DEPENDENCY,
    'adaptive_wccu_unguided_certificate': PolicyMode.ADAPTIVE_WCCU_UNGUIDED_CERTIFICATE,
    'adaptive_policy': PolicyMode.ADAPTIVE,
    'adaptive_readset_occ': PolicyMode.ADAPTIVE_READSET_OCC,
    'uniform_snapshot_occ': PolicyMode.UNIFORM_SNAPSHOT_OCC,
    'uniform_review_gated': PolicyMode.UNIFORM_REVIEW_GATED,
    'uniform_append_only': PolicyMode.UNIFORM_APPEND_ONLY,
}


def _conditions(value: str) -> list[str]:
    if not value or value == 'default':
        return DEFAULT_CONDITIONS
    return [v.strip() for v in value.split(',') if v.strip()]


def _make_writer_intent(*, writer_idx: int, target_id: str, dep_id: str, use_witness: bool) -> dict[str, Any]:
    # Keep dependency terms out of canonical_text_en when use_witness=True so
    # this stress test measures runtime-witness WCCU, not lexical overlap.
    payload_text = (
        f'Apply low-risk output profile patch {writer_idx}.'
        if use_witness
        else f'Apply low-risk patch {writer_idx} that depends on {dep_id} remaining fresh.'
    )
    intent: dict[str, Any] = {
        'intent_type': 'patch_atom',
        'risk': 'low',
        'payload': {
            'id': target_id,
            'atom_id': target_id,
            'target_id': target_id,
            'atom_type': 'memory',
            'title': f'Response-format target {writer_idx}',
            'canonical_text_en': payload_text,
            'reason': 'Generated by randomized WCCU stress runner.',
        },
    }
    if use_witness:
        intent['execution_witness'] = {
            'read_atoms': [dep_id],
            'read_dependencies': [{'target_id': dep_id, 'freshness_required': True, 'reason': 'stress-runner runtime read witness'}],
        }
        intent['projection_witness'] = {'read_atoms': [dep_id]}
    else:
        # Keep the oracle dependency in the scenario for evaluation metrics, but
        # remove all dependency sources that WCCU/read-set OCC are allowed to use.
        # This makes the no-witness stress condition a real boundary diagnostic.
        intent['disable_text_fallback'] = True
        intent['disable_trace_text_fallback'] = True
        intent['disable_projection_trace_witness'] = True
        intent['disable_witness_inference'] = True
    return intent


def _make_invalidator_intent(*, dep_id: str) -> dict[str, Any]:
    return {
        'intent_type': 'retract_atom',
        'authority': 'user',
        'risk': 'low',
        'payload': {
            'id': dep_id,
            'atom_id': dep_id,
            'target_id': dep_id,
            'atom_type': 'memory',
            'status': 'retracted',
            'title': f'Retract {dep_id}',
            'canonical_text_en': f'Retract stale dependency {dep_id}.',
        },
    }


def generate_stress_scenario(*, case_idx: int, writers: int, atom_count: int, invalidation_prob: float, seed: int, use_witness: bool = True) -> dict[str, Any]:
    rng = random.Random(f'{seed}:{case_idx}')
    dep_ids = [f'atom_dep_{case_idx}_{i}' for i in range(atom_count)]
    target_ids = [f'atom_target_{case_idx}_{i}' for i in range(writers)]
    atoms: list[dict[str, Any]] = []
    for dep_id in dep_ids:
        atoms.append({
            'id': dep_id,
            'atom_type': 'memory',
            'title': f'Synthetic dependency {dep_id}',
            'canonical_text_en': f'Runtime fact object {dep_id} with randomized content {rng.randint(0, 10**6)}.',
            'tags': ['wccu_stress', 'dependency', dep_id],
            'status': 'active',
        })
    for target_id in target_ids:
        atoms.append({
            'id': target_id,
            'atom_type': 'memory',
            'title': f'Synthetic write target {target_id}',
            'canonical_text_en': 'Baseline low-risk target.',
            'tags': ['wccu_stress', 'target', target_id],
            'status': 'active',
        })
    agents: list[dict[str, str]] = []
    agent_outputs: dict[str, Any] = {}
    wccu_deps: dict[str, Any] = {}
    invalidated: set[str] = set()
    for i, target_id in enumerate(target_ids):
        dep_id = rng.choice(dep_ids)
        writer_id = f'writer_{i}'
        agents.append({'id': writer_id, 'role': 'agent'})
        agent_outputs[writer_id] = {
            'text': f'Writer {i} proposes a low-risk target update.',
            'intents': [_make_writer_intent(writer_idx=i, target_id=target_id, dep_id=dep_id, use_witness=use_witness)],
        }
        wccu_deps[writer_id] = [{'target_id': dep_id, 'expected_status': 'active', 'freshness_required': True, 'reason': 'stress oracle for accepted-stale counting'}]
        if rng.random() < invalidation_prob:
            invalidated.add(dep_id)
    for j, dep_id in enumerate(sorted(invalidated)):
        invalidator_id = f'invalidator_{j}'
        agents.append({'id': invalidator_id, 'role': 'user'})
        agent_outputs[invalidator_id] = {
            'text': f'User correction retracts {dep_id}.',
            'intents': [_make_invalidator_intent(dep_id=dep_id)],
        }
    expected_by_condition = {
        'adaptive_wccu_execution_trace': {'max_stale_dependency_accepted_count': 0, 'max_unsafe_auto_commit_count': 0},
        'adaptive_wccu_projection_trace': {'max_stale_dependency_accepted_count': 0, 'max_unsafe_auto_commit_count': 0},
        'adaptive_wccu_no_read_validation': {'min_stale_read_validation_ignored_count': 1 if invalidated else 0},
        'adaptive_wccu_execution_trace': {'max_stale_dependency_accepted_count': 0, 'max_unsafe_auto_commit_count': 0},
        'adaptive_wccu_projection_trace': {'max_stale_dependency_accepted_count': 0, 'max_unsafe_auto_commit_count': 0},
        'adaptive_wccu_no_read_validation': {'min_stale_read_validation_ignored_count': 1 if invalidated else 0},
        'adaptive_policy': {'min_stale_dependency_accepted_count': 1 if invalidated else 0},
        'adaptive_readset_occ': {'max_stale_dependency_accepted_count': 0, 'max_unsafe_auto_commit_count': 0},
        'uniform_snapshot_occ': {'min_stale_dependency_accepted_count': 1 if invalidated else 0},
        'uniform_review_gated': {'max_stale_dependency_accepted_count': 0, 'max_unsafe_auto_commit_count': 0},
    }
    return {
        'id': f'wccu_stress_{case_idx:04d}',
        'goal': f'Randomized WCCU stale-dependency stress case {case_idx} with {writers} writers.',
        'task_type': 'wccu_randomized_stress',
        'default_latency_ms': 0,
        'budget_tokens': 8000,
        'agents': agents,
        'seed': {'atoms': atoms, 'links': []},
        'agent_outputs': agent_outputs,
        'wccu_read_dependencies': wccu_deps,
        'expected_by_condition': expected_by_condition,
        'metadata': {
            'case_idx': case_idx,
            'writers': writers,
            'atom_count': atom_count,
            'invalidated_dependency_count': len(invalidated),
            'use_witness': use_witness,
        },
    }


def run_wccu_stress(*, cases: int, writers: int, atom_count: int, invalidation_prob: float, seed: int, condition: str, repetitions: int, out: str, use_witness: bool = True) -> dict[str, Any]:
    conditions = _conditions(condition)
    for cond in conditions:
        if cond not in CONDITION_TO_POLICY:
            raise KeyError(f'Unsupported condition: {cond}')
    out_path = (REPO_ROOT / out).resolve() if not Path(out).is_absolute() else Path(out)
    ensure_dir(out_path.parent)
    jsonl_path = out_path.with_suffix('.jsonl')
    if jsonl_path.exists():
        jsonl_path.unlink()
    tmp_root = REPO_ROOT / 'runs' / f"wccu_stress_{stable_hash(f'{out}:{os.getpid()}:{now_iso()}')}"
    remove_dir(tmp_root)
    results: list[dict[str, Any]] = []
    scenarios = [generate_stress_scenario(case_idx=i, writers=writers, atom_count=atom_count, invalidation_prob=invalidation_prob, seed=seed, use_witness=use_witness) for i in range(cases)]
    for sc in scenarios:
        for cond in conditions:
            for rep in range(max(1, repetitions)):
                run_dir = tmp_root / f"{sc['id']}_{cond}_{rep}"
                root_dir = run_dir / 'context_substrate'
                remove_dir(run_dir)
                seed_context(root_dir, sc.get('seed', {}))
                row = execute_context_policy_parallel(
                    root_dir=root_dir,
                    run_dir=run_dir,
                    scenario=sc,
                    policy_mode=CONDITION_TO_POLICY[cond],
                    condition=cond,
                    # Full-witness stress uses the scenario-declared oracle reads
                    # as runtime witness inputs.  No-witness stress disables the
                    # compiler while retaining those oracle reads only for
                    # evaluation-time stale-accept counting.
                    agent_runner_config={'witness_compiler_enabled': bool(use_witness)},
                )
                row = {**row, 'repetition': rep, 'stress_metadata': sc.get('metadata', {})}
                results.append(row)
                append_jsonl(jsonl_path, row)
    payload = {
        'kind': 'wccu_randomized_stress_results_v1',
        'generated_at': now_iso(),
        'args': {
            'cases': cases,
            'writers': writers,
            'atom_count': atom_count,
            'invalidation_prob': invalidation_prob,
            'seed': seed,
            'condition': condition,
            'repetitions': repetitions,
            'out': str(out),
            'use_witness': use_witness,
        },
        'results': results,
        'aggregated': aggregate(results),
    }
    write_json(out_path, payload)
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description='Run randomized WCCU stale-dependency stress diagnostics.')
    parser.add_argument('--cases', type=int, default=50)
    parser.add_argument('--writers', type=int, default=4)
    parser.add_argument('--atom-count', type=int, default=24)
    parser.add_argument('--invalidation-prob', type=float, default=0.35)
    parser.add_argument('--seed', type=int, default=7)
    parser.add_argument('--condition', default='default')
    parser.add_argument('--repetitions', type=int, default=1)
    parser.add_argument('--out', default='results/wccu_randomized_stress.json')
    parser.add_argument('--no-witness', action='store_true', help='Disable explicit runtime witnesses and rely on text-overlap fallback only.')
    args = parser.parse_args(argv)
    payload = run_wccu_stress(
        cases=args.cases,
        writers=args.writers,
        atom_count=args.atom_count,
        invalidation_prob=args.invalidation_prob,
        seed=args.seed,
        condition=args.condition,
        repetitions=args.repetitions,
        out=args.out,
        use_witness=not args.no_witness,
    )
    print(json.dumps({'ok': True, 'out': payload['args']['out'], 'result_count': len(payload['results']), 'aggregate_count': len(payload['aggregated'])}, indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
